package tsbuf_test

import (
	"strings"
	"testing"

	"github.com/simonjanss/rig/internal/gen/tsbuf"
)

func render(t *testing.T, b *tsbuf.Buf) string {
	t.Helper()
	out, err := b.Bytes()
	if err != nil {
		t.Fatal(err)
	}
	return string(out)
}

func TestAGeneratedFileCarriesTheBanner(t *testing.T) {
	t.Parallel()

	src := render(t, tsbuf.New())
	if !strings.HasPrefix(src, "// Code generated by rig. DO NOT EDIT.\n") {
		t.Errorf("no banner:\n%s", src)
	}
}

// A file a developer owns is written once and then theirs, so a banner telling
// them not to edit it would be a lie the first time they needed to.
func TestAHandOwnedFileHasNoBanner(t *testing.T) {
	t.Parallel()

	src := render(t, tsbuf.NewHandOwned())
	if strings.Contains(src, "DO NOT EDIT") {
		t.Errorf("a hand-owned file should carry no banner:\n%s", src)
	}
}

// Types before values, each group sorted by module — which puts a relative
// specifier before a package one, since "." sorts below "@". It is what the
// hand-written packages look like, and a generated file that ordered its imports
// differently from every file beside it would read as a different codebase.
func TestTypeImportsComeFirstAndBothAreSorted(t *testing.T) {
	t.Parallel()

	b := tsbuf.NewHandOwned()
	b.Import("./zeta.js", "zeta")
	b.Import("@rig-ts/client", "send")
	b.ImportType("./alpha.js", "Alpha")
	b.ImportType("@rig-ts/client", "Runtime")
	b.L("const x = 1;")

	want := strings.Join([]string{
		`import type { Alpha } from "./alpha.js";`,
		`import type { Runtime } from "@rig-ts/client";`,
		``,
		`import { zeta } from "./zeta.js";`,
		`import { send } from "@rig-ts/client";`,
		``,
		`const x = 1;`,
		``,
	}, "\n")

	if got := render(t, b); got != want {
		t.Errorf("got:\n%s\nwant:\n%s", got, want)
	}
}

// The same module imported for values and for types is two statements, because
// `import type` is what says the import disappears at build time.
func TestOneModuleCanBeImportedTwoWays(t *testing.T) {
	t.Parallel()

	b := tsbuf.NewHandOwned()
	b.Import("@rig-ts/client", "Runtime")
	b.ImportType("@rig-ts/client", "Config")

	src := render(t, b)
	if !strings.Contains(src, `import type { Config } from "@rig-ts/client";`) {
		t.Errorf("no type import:\n%s", src)
	}
	if !strings.Contains(src, `import { Runtime } from "@rig-ts/client";`) {
		t.Errorf("no value import:\n%s", src)
	}
}

func TestRepeatedImportsCollapse(t *testing.T) {
	t.Parallel()

	b := tsbuf.NewHandOwned()
	b.Import("@rig-ts/client", "send")
	b.Import("@rig-ts/client", "send")
	b.Import("@rig-ts/client", "pathValue")

	want := `import { pathValue, send } from "@rig-ts/client";`
	if got := render(t, b); !strings.Contains(got, want) {
		t.Errorf("got:\n%s\nwant a line:\n%s", got, want)
	}
}

// Nothing in the Go toolchain formats TypeScript, so the emitter is the only
// place the layout can come from. A long import is wrapped the way Prettier
// would have wrapped it.
func TestALongImportWraps(t *testing.T) {
	t.Parallel()

	b := tsbuf.NewHandOwned()
	for _, name := range []string{
		"LessonCreateFields", "LessonCreateInput", "LessonListDeletedQuery",
		"LessonListQuery", "LessonSearchQuery",
	} {
		b.ImportType("./lesson_input.gen.js", name)
	}

	src := render(t, b)
	if !strings.Contains(src, "import type {\n    LessonCreateFields,\n") {
		t.Errorf("a long import should wrap one name per line:\n%s", src)
	}
	for line := range strings.SplitSeq(src, "\n") {
		if len(line) > 80 {
			t.Errorf("line over 80 columns: %q", line)
		}
	}
}

// A short one does not, because Prettier would not have.
func TestAShortImportStaysOnOneLine(t *testing.T) {
	t.Parallel()

	b := tsbuf.NewHandOwned()
	b.ImportType("./lesson.gen.js", "Lesson")

	if got := render(t, b); got != "import type { Lesson } from \"./lesson.gen.js\";\n\n" {
		t.Errorf("unexpected:\n%q", got)
	}
}

func TestAOneLineCommentStaysOnOneLine(t *testing.T) {
	t.Parallel()

	b := tsbuf.NewHandOwned()
	b.Comment("Unique identifier for this row.")

	if got := render(t, b); got != "/** Unique identifier for this row. */\n" {
		t.Errorf("unexpected:\n%q", got)
	}
}

func TestALongCommentWrapsIntoABlock(t *testing.T) {
	t.Parallel()

	b := tsbuf.NewHandOwned()
	b.Comment(strings.Repeat("word ", 40))

	src := render(t, b)
	if !strings.HasPrefix(src, "/**\n * word") {
		t.Errorf("expected a block comment:\n%s", src)
	}
	for line := range strings.SplitSeq(src, "\n") {
		if len(line) > 80 {
			t.Errorf("line over 80 columns: %q", line)
		}
	}
}

// A blank line between paragraphs survives, because that is what makes the
// second paragraph of a description readable rather than a run-on.
func TestParagraphsAreKeptApart(t *testing.T) {
	t.Parallel()

	b := tsbuf.NewHandOwned()
	b.Comment("First.\n\nSecond.")

	want := "/**\n * First.\n *\n * Second.\n */\n"
	if got := render(t, b); got != want {
		t.Errorf("got:\n%q\nwant:\n%q", got, want)
	}
}

// Rewrapping an indented block would break the code in it.
func TestAnIndentedBlockIsLeftAlone(t *testing.T) {
	t.Parallel()

	b := tsbuf.NewHandOwned()
	b.Comment("Like this:\n\n    const x = 1;\n    const y = 2;")

	src := render(t, b)
	if !strings.Contains(src, " *     const x = 1;\n *     const y = 2;\n") {
		t.Errorf("the block was reflowed:\n%s", src)
	}
}

// A comment inside a type is wrapped to what is left after the indentation, or
// the block runs past the margin the rest of the file keeps to.
func TestACommentWrapsToWhatTheIndentationLeaves(t *testing.T) {
	t.Parallel()

	b := tsbuf.NewHandOwned()
	b.L("export type X = {")
	b.Indent()
	b.Comment(strings.Repeat("word ", 40))
	b.Outdent()
	b.L("};")

	for line := range strings.SplitSeq(render(t, b), "\n") {
		if len(line) > 80 {
			t.Errorf("line over 80 columns: %q", line)
		}
	}
}

func TestIndentAndOutdent(t *testing.T) {
	t.Parallel()

	b := tsbuf.NewHandOwned()
	b.L("a")
	b.Indent()
	b.L("b")
	b.Indent()
	b.L("c")
	b.Outdent()
	b.Outdent()
	// One more than there are levels, so a mismatched pair cannot make the rest
	// of a file negative-indented.
	b.Outdent()
	b.L("d")

	want := "a\n    b\n        c\nd\n"
	if got := render(t, b); got != want {
		t.Errorf("got:\n%q\nwant:\n%q", got, want)
	}
}

func TestPAndNLBuildALineByHand(t *testing.T) {
	t.Parallel()

	b := tsbuf.NewHandOwned()
	b.Indent()
	b.P("const all = [")
	b.P("%q, ", "a")
	b.P("%q", "b")
	b.L("];")

	want := "    const all = [\"a\", \"b\"];\n"
	if got := render(t, b); got != want {
		t.Errorf("got:\n%q\nwant:\n%q", got, want)
	}
}

// A column called `order` is a fine key; one called `full-name` is not, and
// emitting it bare would be a syntax error rather than a wrong name.
func TestAKeyIsQuotedOnlyWhenItHasToBe(t *testing.T) {
	t.Parallel()

	for _, tc := range []struct{ in, want string }{
		{"id", "id"},
		{"created_at", "created_at"},
		{"$ref", "$ref"},
		{"_private", "_private"},
		{"x2", "x2"},
		{"full-name", `"full-name"`},
		{"2fa", `"2fa"`},
		{"a b", `"a b"`},
		{"", `""`},
	} {
		if got := tsbuf.Key(tc.in); got != tc.want {
			t.Errorf("Key(%q) = %q, want %q", tc.in, got, tc.want)
		}
	}
}

func TestQuoteEscapes(t *testing.T) {
	t.Parallel()

	if got := tsbuf.Quote(`a"b`); got != `"a\"b"` {
		t.Errorf("Quote = %s", got)
	}
}
